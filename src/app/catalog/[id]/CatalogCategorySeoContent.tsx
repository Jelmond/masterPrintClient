type Props = {
    slug: string
    tagSlug?: string
}

export function CatalogCategorySeoContent({ slug, tagSlug }: Props) {
    if (tagSlug) {
        const tagBlock = CATALOG_TAG_SEO_CONTENT[`${slug}/${tagSlug}`]
        if (tagBlock) {
            return <SeoContent lead={tagBlock.lead}>{tagBlock.content}</SeoContent>
        }
    }
    const seoContent = CATALOG_SEO_CONTENT[slug]
    if (!seoContent) return null
    return <SeoContent>{seoContent}</SeoContent>
}
